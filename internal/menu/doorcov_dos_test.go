// doorcovBatch writes EXTERNAL.BAT for cfg on node 3 and returns its lines.
func doorcovBatch(t *testing.T, cfg config.DoorConfig) []string {
	t.Helper()
	ctx := &DoorCtx{
		Config:     cfg,
		NodeNumStr: "3",
		Subs:       map[string]string{"{DOSDROPFILE}": `C:\NODES\TEMP3\DOOR.SYS`, "{USERHANDLE}": "Neo"},
	}
	path := filepath.Join(t.TempDir(), "EXTERNAL.BAT")
	if err := writeBatchFile(ctx, path); err != nil {
		t.Fatalf("writeBatchFile: %v", err)
	}
	if fi, err := os.Stat(path); err != nil || fi.Mode().Perm() != 0o600 {
		t.Errorf("batch file mode %v, err %v; want 0600", fi.Mode().Perm(), err)
	}
	return doorcovLines(t, path)
}

func TestDoorcovWriteBatchFile(t *testing.T) {
	for _, tc := range []struct {
		name string
		cfg  config.DoorConfig
		want []string
	}{
		{
			"bare command",
			config.DoorConfig{Commands: []string{"LORD.EXE /N{NODE} /D{DOSDROPFILE} {USERHANDLE}"}},
			[]string{"@echo off", `SET PATH=%PATH%;D:\dosemu`, "c:", "cls",
				`LORD.EXE /N3 /DC:\NODES\TEMP3\DOOR.SYS Neo`, "exitemu"},
		},
		{
			// The FOSSIL driver loads before the screen clear that marks the
			// end of boot, and the door's drive is selected before its cd.
			"fossil driver and working directory",
			config.DoorConfig{
				FossilDriver:     `C:\UTILS\X00.EXE eliminate`,
				WorkingDirectory: `D:\DOORS\LORD GAME`,
				Commands:         []string{"START.EXE"},
			},
			[]string{"@echo off", `SET PATH=%PATH%;D:\dosemu`, "c:", `C:\UTILS\X00.EXE eliminate`, "cls",
				"D:", `cd "D:\DOORS\LORD GAME"`, "START.EXE", "exitemu"},
		},
		{
			"working directory without a drive",
			config.DoorConfig{WorkingDirectory: `\DOORS`, Commands: nil},
			[]string{"@echo off", `SET PATH=%PATH%;D:\dosemu`, "c:", "cls", `cd "\DOORS"`, "exitemu"},
		},
		{
			// A batch file run without CALL never returns, so exitemu would
			// not run; only a line whose program is a .BAT gets one.
			"batch files are called",
			config.DoorConfig{Commands: []string{
				"start.bat {NODE}", "CALL SETUP.BAT", "  call other.bat", "EDIT.EXE NOTES.BAT", "",
			}},
			[]string{"@echo off", `SET PATH=%PATH%;D:\dosemu`, "c:", "cls",
				"CALL start.bat 3", "CALL SETUP.BAT", "  call other.bat", "EDIT.EXE NOTES.BAT", "", "exitemu"},
		},
	} {
		t.Run(tc.name, func(t *testing.T) {
			got := doorcovBatch(t, tc.cfg)
			if strings.Join(got, "\n") != strings.Join(tc.want, "\n") {
				t.Errorf("EXTERNAL.BAT =\n%s\nwant\n%s", strings.Join(got, "\n"), strings.Join(tc.want, "\n"))
			}
		})
	}
}

